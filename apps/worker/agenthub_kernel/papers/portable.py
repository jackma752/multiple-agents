"""Deterministic portable research outputs, built only from recorded exports.

No model, network or compiler is invoked. HTML is printable offline; LaTeX is
source for the user's own XeLaTeX setup; DOCX is an editable text draft with
math source preserved (not an equation-layout conversion). No original PDFs,
credentials or runtime databases are included in the evidence bundle.
"""
from __future__ import annotations

import hashlib
import html
import io
import json
import re
import zipfile
from xml.sax.saxutils import escape


def archive(files: dict[str, bytes]) -> bytes:
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w", compression=zipfile.ZIP_DEFLATED) as z:
        for name, data in sorted(files.items()):
            info = zipfile.ZipInfo(name, (2020, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(info, data)
    return out.getvalue()


def _lines(md):
    code = False
    for line in md.splitlines():
        if line.startswith("```"):
            code = not code
            continue
        # Disclosure tags are generated by our guidance exporter, never rendered as HTML.
        if re.fullmatch(r"</?details>|<details><summary>.*</summary>", line.strip()): continue
        heading = re.match(r"^(#{1,6})\s+(.*)", line) if not code else None
        yield (len(heading[1]) if heading else 0, heading[2] if heading else line, code)


def html_document(md: str) -> bytes:
    lines = []
    for level, line, code in _lines(md):
        tag = f"h{level}" if level else "pre" if code else "p"
        lines.append(f"<{tag}>{html.escape(line)}</{tag}>")
    body = ('<!doctype html><html lang="zh"><meta charset="utf-8"><title>研究成果</title>'
            '<meta name="viewport" content="width=device-width,initial-scale=1">'
            '<style>body{max-width:900px;margin:32px auto;padding:20px;font:16px/1.8 system-ui;overflow-wrap:anywhere}'
            'pre{white-space:pre-wrap;background:#f5f5f5;padding:8px}h1,h2,h3{break-after:avoid}'
            '@media print{body{margin:0;max-width:none}} </style>'
            '<p>离线阅读/打印版本。数学公式保留 LaTeX 源文；精确排版请使用提供的 Markdown 或 LaTeX 源文件。</p>'
            + "\n".join(lines) + '</html>')
    return body.encode("utf-8")


def _tex_text(s):
    chars = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
             "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(chars.get(c, c) for c in s)


def tex_document(md: str) -> bytes:
    body = []
    for level, line, code in _lines(md):
        # Treat all prose as text, including arbitrary model-produced TeX commands.
        value = _tex_text(line)
        if level:
            command = ("section", "subsection", "subsubsection")[min(level, 3)-1]
            body.append("\\" + command + "*{" + value + "}")
        else: body.append((r"\texttt{" + value + "}" if code else value) + "\n")
    return (r"\documentclass[UTF8]{ctexart}" + "\n" + r"\usepackage[margin=25mm]{geometry}" + "\n"
            + r"\begin{document}" + "\n" + "\n".join(body) + "\n" + r"\end{document}" + "\n").encode("utf-8")


def docx_document(md: str) -> bytes:
    paragraphs = []
    note = "可编辑文字稿：数学公式保留 LaTeX 源文；此文件不代表公式排版或科研质量已经核查。"
    for level, line, code in [(0, note, False), *_lines(md)]:
        # XML 1.0 excludes controls, while tabs and newlines are allowed.
        line = "".join(c for c in line if ord(c) >= 32 or c in "\t\n")
        props = f'<w:pStyle w:val="Heading{min(level,3)}"/>' if level else ''
        run = '<w:rFonts w:ascii="Consolas" w:eastAsia="宋体"/>' if code else ''
        paragraphs.append(f'<w:p><w:pPr>{props}</w:pPr><w:r><w:rPr>{run}</w:rPr>'
                          f'<w:t xml:space="preserve">{escape(line)}</w:t></w:r></w:p>')
    ns = 'xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"'
    document = (f'<?xml version="1.0" encoding="UTF-8"?><w:document {ns}><w:body>' + ''.join(paragraphs)
                + '<w:sectPr><w:pgSz w:w="11906" w:h="16838"/><w:pgMar w:top="1440" w:right="1440" '
                  'w:bottom="1440" w:left="1440"/></w:sectPr></w:body></w:document>')
    styles = f'<w:styles {ns}><w:docDefaults><w:rPrDefault><w:rPr><w:rFonts w:ascii="Calibri" w:eastAsia="宋体"/>' \
             '<w:sz w:val="22"/></w:rPr></w:rPrDefault></w:docDefaults>'
    for n, size in [(1,32),(2,28),(3,24)]:
        styles += f'<w:style w:type="paragraph" w:styleId="Heading{n}"><w:name w:val="heading {n}"/>' \
                  f'<w:pPr><w:keepNext/><w:outlineLvl w:val="{n-1}"/></w:pPr><w:rPr><w:b/><w:sz w:val="{size}"/></w:rPr></w:style>'
    styles += '</w:styles>'
    files = {'[Content_Types].xml': b'<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
              b'<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
              b'<Default Extension="xml" ContentType="application/xml"/>'
              b'<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>'
              b'<Override PartName="/word/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.styles+xml"/></Types>',
             '_rels/.rels': b'<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
              b'<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>',
             'word/_rels/document.xml.rels': b'<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
              b'<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/></Relationships>',
             'word/document.xml': document.encode('utf-8'), 'word/styles.xml': styles.encode('utf-8')}
    return archive(files)


def enrich(files: dict[str, bytes]) -> dict[str, bytes]:
    result = dict(files)
    for name, data in files.items():
        if not name.endswith('.md'): continue
        md = data.decode('utf-8')
        stem = name[:-3]
        result[stem+'.html'] = html_document(md)
        result[stem+'.tex'] = tex_document(md)
        result[stem+'.docx'] = docx_document(md)
    result['EXPORT-README.txt'] = ("研究成果包：正文、结构化资料及可编辑副本。\n"
        "HTML 可离线阅读并由浏览器打印为 PDF；DOCX/LaTeX 是文字稿，数学公式保留源文。\n"
        "未自动运行 LaTeX 编译器，不承诺出版级公式排版。质量状态以研究报告为准。\n"
        "不含原始论文 PDF、账号密钥或运行数据库。\n").encode('utf-8')
    result['MANIFEST.json'] = json.dumps({name:{'size':len(data),'sha256':hashlib.sha256(data).hexdigest()}
        for name,data in sorted(result.items())},ensure_ascii=False,indent=2).encode('utf-8')
    result['research-bundle.zip'] = archive(result)
    return result
